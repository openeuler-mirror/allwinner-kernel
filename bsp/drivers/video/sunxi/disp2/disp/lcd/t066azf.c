{
	sunxi_lcd_pin_cfg(sel, 0);
	sunxi_lcd_delay_ms(20);
	sunxi_lcd_power_disable(sel, 0);
	sunxi_lcd_delay_ms(50);
	// sunxi_lcd_dsi_clk_disable(sel);
}

